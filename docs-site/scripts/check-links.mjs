#!/usr/bin/env node
// Internal link check over the BUILT site (#1271).
//
// `mkdocs build --strict` fails on a broken internal link; `astro build` does
// not. This closes that gap without a new dependency.
//
// Definition of "a link" (so the count is reproducible): every <a> element
// whose href starts with "/" or "#", inside the <main>...</main> element of
// every page in dist/. That includes the heading self-links Starlight adds
// (class sl-anchor-link), reported separately, and excludes non-<a> hrefs such
// as the Expressive Code <link rel="stylesheet"> Starlight emits inside <main>.
// Header, sidebar, footer and <head> links are excluded: they are generated by
// Starlight from config, not written in content. A link resolves
// when dist/<path>/index.html (or dist/<path>) exists and, if it has a
// fragment, that page has an element with that id ("#_top" is Starlight's
// built-in page-top anchor and always counts).
//
// Usage (from docs-site/, after `npm run build`): node scripts/check-links.mjs
// Exit 1 on any broken link.

import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const dist = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist')
if (!existsSync(dist)) {
  console.error('no dist/: run `npm run build` first')
  process.exit(2)
}
const walk = (d) =>
  readdirSync(d).flatMap((n) => {
    const p = join(d, n)
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.html') ? [p] : []
  })

const idCache = new Map()
const idsOf = (file) => {
  if (!idCache.has(file)) {
    idCache.set(file, new Set([...readFileSync(file, 'utf8').matchAll(/ id="([^"]+)"/g)].map((m) => m[1])))
  }
  return idCache.get(file)
}

let pages = 0, links = 0, selfLinks = 0, broken = 0
for (const page of walk(dist)) {
  const html = readFileSync(page, 'utf8')
  const main = /<main\b[^>]*>([\s\S]*?)<\/main>/.exec(html)?.[1]
  if (main === undefined) continue
  pages++
  for (const m of main.matchAll(/<a\b[^>]*\bhref="(\/[^"]*|#[^"]+)"[^>]*>/g)) {
    links++
    if (/\bsl-anchor-link\b/.test(m[0])) selfLinks++
    const [path, anchor] = m[1].split('#')
    let target = page
    if (path) {
      const asDir = join(dist, path, 'index.html')
      const asFile = join(dist, path)
      target = existsSync(asDir) ? asDir : existsSync(asFile) && statSync(asFile).isFile() ? asFile : null
    }
    if (!target || (anchor && anchor !== '_top' && !idsOf(target).has(decodeURIComponent(anchor)))) {
      broken++
      console.log(`BROKEN ${page.slice(dist.length)} -> ${m[1]}`)
    }
  }
}
console.log(
  `pages ${pages}; internal <a href> links inside <main> ${links} ` +
    `(${selfLinks} heading self-links Starlight generates, ${links - selfLinks} written in content); broken ${broken}`,
)
process.exit(broken ? 1 : 0)
